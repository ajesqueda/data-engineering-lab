"""PostgreSQL DDL for the model: one transaction, so a deploy is all or nothing."""

from __future__ import annotations

from .model import Table, literal

SHORT = {"timestamp with time zone": "timestamptz"}


def _column_sql(col, fk, width: int) -> str:
    parts = [col.name.ljust(width), SHORT.get(col.type, col.type)]
    if col.identity:
        parts.append("GENERATED ALWAYS AS IDENTITY PRIMARY KEY")
    elif col.not_null:
        parts.append("NOT NULL")
    if col.default:
        parts.append(f"DEFAULT {col.default}")
    if col.unique:
        parts.append("UNIQUE")
    if fk is not None:
        parts.append(f"REFERENCES {fk.references} ({fk.references}_id) "
                     f"ON DELETE {fk.on_delete.upper()}")
    if col.check:
        parts.append(f"CHECK ({col.check})")
    return " ".join(parts)


def create_table(table: Table, created: set[str]) -> tuple[str, list[str]]:
    """CREATE TABLE plus the ALTERs for links to tables that don't exist yet."""
    width = max(len(c.name) for c in table.columns)
    fks = {fk.column: fk for fk in table.foreign_keys}
    inline_ok = created | {table.name}
    later = []
    lines = []
    for col in table.columns:
        fk = fks.get(col.name)
        if fk is not None and fk.references not in inline_ok:
            later.append(f"ALTER TABLE {table.name} ADD FOREIGN KEY ({col.name}) "
                         f"REFERENCES {fk.references} ({fk.references}_id) "
                         f"ON DELETE {fk.on_delete.upper()};")
            fk = None
        lines.append("    " + _column_sql(col, fk, width))
    if not any(c.identity for c in table.columns):
        lines.append(f"    PRIMARY KEY ({', '.join(table.primary_key)})")
    for group in table.unique_together:
        lines.append(f"    UNIQUE ({', '.join(group)})")
    sql = [f"CREATE TABLE {table.name} (", ",\n".join(lines), ");"]
    if table.comment:
        sql.append(f"COMMENT ON TABLE {table.name} IS {literal(table.comment)};")
    for col in table.columns:
        if col.comment:
            sql.append(f"COMMENT ON COLUMN {table.name}.{col.name} IS {literal(col.comment)};")
    for column in table.fk_indexes():
        sql.append(f"CREATE INDEX {table.name}_{column}_idx ON {table.name} ({column});")
    return "\n".join(sql), later


def render(tables: list[Table], schema: str, replace: bool = False,
           source: str | None = None, description: str | None = None) -> str:
    """The whole schema as one script, wrapped in BEGIN ... COMMIT.

    Run with `psql -v ON_ERROR_STOP=1`: on the first error psql stops before COMMIT,
    and the transaction is rolled back, so nothing half-built is left behind.
    """
    head = [f"-- {schema}: generated by schema-starter" + (f" from {source}" if source else ""),
            "BEGIN;"]
    if replace:
        head.append(f"DROP SCHEMA IF EXISTS {schema} CASCADE;  -- --replace: start over")
    head.append(f"CREATE SCHEMA {schema};")
    if description:
        head.append(f"COMMENT ON SCHEMA {schema} IS {literal(description)};")
    head.append(f"SET LOCAL search_path TO {schema};")
    body, later, created = [], [], set()
    for table in tables:
        sql, alters = create_table(table, created)
        body.append(sql)
        later += alters
        created.add(table.name)
    tail = (["-- links to tables created later in this script"] + later) if later else []
    return "\n\n".join(["\n".join(head), *body, *(["\n".join(tail)] if tail else []),
                        "COMMIT;"]) + "\n"
